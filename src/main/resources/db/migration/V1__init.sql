-- Written to run unchanged on H2 (MODE=PostgreSQL) and PostgreSQL.

CREATE TABLE payment (
    id                  VARCHAR(36)    PRIMARY KEY,
    idempotency_key     VARCHAR(100)   NOT NULL,
    request_hash        VARCHAR(64)    NOT NULL,
    source_account      VARCHAR(20)    NOT NULL,
    destination_name    VARCHAR(140)   NOT NULL,
    destination_account VARCHAR(20)    NOT NULL,
    amount              NUMERIC(19, 4) NOT NULL,
    currency            VARCHAR(3)     NOT NULL,
    reference           VARCHAR(35)    NOT NULL,
    execution_date      DATE           NOT NULL,
    status              VARCHAR(20)    NOT NULL,
    fraud_decision      VARCHAR(10),
    fraud_risk_score    NUMERIC(5, 2),
    fraud_reasons       VARCHAR(2000),
    fraud_checked_at    TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT         NOT NULL,
    CONSTRAINT uq_payment_idempotency_key UNIQUE (idempotency_key)
);

-- Transactional outbox: written in the SAME transaction as the payment row.
CREATE TABLE outbox_event (
    id              VARCHAR(36)   PRIMARY KEY,   -- doubles as the event id
    aggregate_id    VARCHAR(36)   NOT NULL,
    event_type      VARCHAR(50)   NOT NULL,
    payload         VARCHAR(4000) NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    attempts        INT           NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error      VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_outbox_due ON outbox_event (status, next_attempt_at);

-- Durable broker stub: one row per (event, subscriber). Stands in for a Kafka topic + consumer group.
-- Deliberately NO unique constraint: like a real at-least-once broker it can hold duplicates.
CREATE TABLE event_delivery (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(36)   NOT NULL,
    event_type      VARCHAR(50)   NOT NULL,
    consumer        VARCHAR(50)   NOT NULL,
    payload         VARCHAR(4000) NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    attempts        INT           NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error      VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_delivery_due ON event_delivery (consumer, status, next_attempt_at);

-- Consumer-side idempotency ("inbox"): a consumer applies an event at most once.
CREATE TABLE processed_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer     VARCHAR(50) NOT NULL,
    event_id     VARCHAR(36) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_processed_consumer_event UNIQUE (consumer, event_id)
);

-- Ledger: the unique constraint on payment_id is the last line of defence against double posting.
CREATE TABLE ledger_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(36)    NOT NULL,
    account    VARCHAR(20)    NOT NULL,
    direction  VARCHAR(6)     NOT NULL,
    amount     NUMERIC(19, 4) NOT NULL,
    currency   VARCHAR(3)     NOT NULL,
    posted_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ledger_payment UNIQUE (payment_id)
);
